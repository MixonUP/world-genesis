"""Generate the executable 0.4 research subset from the authoritative design IDs.
Other design rows are not silently presented as working game systems.
"""
import csv
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
ids = [
    'f01_preservation', 'f07_husbandry', 'm01_forestry', 'c01_herbalism', 'c02_clean_water',
    'l06_paths', 'f06_river_fishing', 'm02_carpentry', 'l01_local_trade',
    'k01_teaching', 'd10_wooden_defenses', 'm10_comfort_housing',
    'k08_apprenticeship', 'm04_brick_firing', 'c03_civic_records',
    'k02_schools', 'c06_stream_management', 'l07_paved_roads',
    't01_flax', 't02_linen', 'l02_carts', 'l03_caravans', 'f02_milling', 'f08_brewing', 'l08_stock_ownership', 'm11_town_houses', 'm12_stone_houses', 'm13_estates',
]
with (root / 'SourceAssets/Design/technologies.csv').open(encoding='utf-8-sig', newline='') as file:
    rows = {r['technology_id']: r for r in csv.DictReader(file)}
lines = []
for key in ids:
    row = rows[key]
    prerequisites = [s for s in row['prerequisites'].split(';') if s]
    assert set(prerequisites) <= set(ids), (key, prerequisites)
    quoted = lambda value: json.dumps(value, ensure_ascii=False)
    lines.append('            new TechnologyDefinition(' + ', '.join([
        quoted(key), quoted(row['name_ru']), row['cost_points'] + 'f',
        'new string[] { ' + ', '.join(quoted(p) for p in prerequisites) + ' }']) + '),')
source = '''// Generated by Tools/Generate-TechnologyCatalog.py; edit the source CSV and regenerate.
namespace WorldGenesis.Simulation
{
    public sealed class TechnologyDefinition
    {
        public readonly string Id, Name;
        public readonly float Cost;
        public readonly string[] Prerequisites;
        public TechnologyDefinition(string id, string name, float cost, string[] prerequisites)
        { Id = id; Name = name; Cost = cost; Prerequisites = prerequisites; }
    }
    public static class TechnologyCatalog
    {
        public static readonly TechnologyDefinition[] All = {
''' + '\n'.join(lines) + '''
        };
        public static TechnologyDefinition Get(string id)
        {
            for (int i = 0; i < All.Length; i++) if (All[i].Id == id) return All[i];
            return null;
        }
    }
}
'''
(root / 'WorldGenesis/Assets/_Project/Scripts/Simulation/Civilizations/TechnologyCatalog.cs').write_text(source, encoding='utf-8', newline='\n')
print(json.dumps({'runtime': len(ids), 'design': len(rows), 'ids': ids}, ensure_ascii=False))
